export function resolveLocale(value) {
  const locale = String(value || "").toLowerCase();
  if (locale === "en" || locale.startsWith("en-")) return "en";
  if (locale === "zh" || locale.startsWith("zh-")) return "zh-CN";
  return DEFAULT_LOCALE;
}

export function createI18n(locale = DEFAULT_LOCALE) {
  const resolved = resolveLocale(locale);
  return {
    locale: resolved,
    t(key, values = {}) {
      const template = translations[resolved][key] ?? translations.en[key] ?? key;
      return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? `{${name}}`));
    }
  };
}

export function localizeIssue(issue, locale = DEFAULT_LOCALE) {
  const resolved = resolveLocale(locale);
  return translations[resolved][`issue.${issue.code}`] || translations[resolved]["issue.invalid_value"];
}
